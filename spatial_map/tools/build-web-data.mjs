import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(__dirname, '..', 'data');
const OUT = DATA;

const parks = JSON.parse(fs.readFileSync(path.join(DATA, 'parks.json'), 'utf8'));
const seats = JSON.parse(fs.readFileSync(path.join(DATA, 'district-seats.json'), 'utf8'));
const districts = JSON.parse(fs.readFileSync(path.join(DATA, 'gujarat-districts.geojson'), 'utf8'));

/* ------------------------------------------------- derived / slim records */

const CONFIDENCE_RANK = { high: 3, medium: 2, low: 1, approximate: 0 };

const slim = parks.map((p) => ({
  id: p.id,
  n: p.name,
  cat: p.categoryShort,
  catFull: p.category,
  d: p.district,
  loc: p.location,
  vil: p.village,
  tal: p.taluka,
  addr: p.address,
  con: p.contact,
  tel: p.phone,
  mail: p.email,
  off: p.office,
  notes: p.notes,
  src: p.source,
  tent: p.tentative,
  phase: p.phaseMatch,
  ind: p.industries,
  ha: p.areaHa,
  appr: p.approval,
  lat: p.lat,
  lng: p.lng,
  gm: p.geo.method,
  gc: p.geo.confidence,
  gp: p.geo.matchedPlace,
  gkm: p.geo.placeDistanceKm ?? null,
  gdisp: p.geo.display ?? null,
}));

/* ------------------------------------------------------------- roll-ups */

const byDistrict = new Map();
const byCategory = new Map();
const byConfidence = new Map();
const byMethod = new Map();
const byIndustry = new Map();

for (const p of slim) {
  const d = byDistrict.get(p.d) ?? { district: p.d, total: 0, gidc: 0, private: 0, tentative: 0, areaHa: 0 };
  d.total++;
  if (p.cat === 'Private') {
    d.private++;
    if (p.ha) d.areaHa += p.ha;
  } else d.gidc++;
  if (p.tent) d.tentative++;
  byDistrict.set(p.d, d);

  byCategory.set(p.cat, (byCategory.get(p.cat) ?? 0) + 1);
  byConfidence.set(p.gc, (byConfidence.get(p.gc) ?? 0) + 1);
  byMethod.set(p.gm, (byMethod.get(p.gm) ?? 0) + 1);

  if (p.ind) {
    for (const part of p.ind.split(/[,;/]/).map((s) => s.trim()).filter(Boolean)) {
      byIndustry.set(part, (byIndustry.get(part) ?? 0) + 1);
    }
  }
}

const stats = {
  total: slim.length,
  districts: byDistrict.size,
  gidc: byCategory.get('GIDC') ?? 0,
  private: byCategory.get('Private') ?? 0,
  tentative: slim.filter((p) => p.tent).length,
  totalAreaHa: +slim.reduce((a, p) => a + (p.ha ?? 0), 0).toFixed(2),
  withArea: slim.filter((p) => p.ha != null).length,
  distinctTalukas: new Set(slim.map((p) => p.loc)).size,
  byConfidence: Object.fromEntries([...byConfidence].sort((a, b) => CONFIDENCE_RANK[b[0]] - CONFIDENCE_RANK[a[0]])),
  byMethod: Object.fromEntries([...byMethod].sort((a, b) => b[1] - a[1])),
  industries: [...byIndustry].sort((a, b) => b[1] - a[1]),
};

const districtRows = [...byDistrict.values()].sort((a, b) => b.total - a.total || a.district.localeCompare(b.district));

/* ------------------------------------------------ emit script-tag bundles */

const banner = '/* Generated by tools/build-web-data.mjs - do not edit by hand. */\n';

function emit(name, globalName, payload) {
  const file = path.join(OUT, name);
  const body = `${banner}window.${globalName} = ${JSON.stringify(payload)};\n`;
  fs.writeFileSync(file, body);
  console.log(`wrote ${file} (${(Buffer.byteLength(body) / 1024).toFixed(1)} KB)`);
}

emit('parks.js', 'GJ_PARKS', slim);
emit('districts.js', 'GJ_DISTRICTS', districts);
emit('meta.js', 'GJ_META', { stats, districtRows, seats, builtFrom: 'Gujarat_Industrial_Parks_and_GIDC_Estates.csv' });

console.log('\nstats:', JSON.stringify({ ...stats, industries: `${stats.industries.length} groups` }, null, 1));
console.log('\ntop districts:');
for (const d of districtRows.slice(0, 8)) {
  console.log(`  ${d.district.padEnd(20)} ${String(d.total).padStart(3)}  gidc=${String(d.gidc).padStart(3)} private=${String(d.private).padStart(2)} tentative=${String(d.tentative).padStart(2)} ${d.areaHa ? `area=${d.areaHa}ha` : ''}`);
}